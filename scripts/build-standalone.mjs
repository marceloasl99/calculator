// Builds standalone.html: a single self-contained file (inline CSS + bundled JS)
// that runs from file:// with a double-click, where ES modules are blocked by browsers.
// Usage: npm run build
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (rel) => fs.readFileSync(path.join(rootDir, rel), 'utf8');

// Dependency order: every module appears after the modules it imports.
const MODULES = [
  'js/expression-parser.js',
  'js/calculator-engine.js',
  'js/formatting.js',
  'js/tools/complex.js',
  'js/tools/matrices.js',
  'js/tools/statistics.js',
  'js/tools/equation-solver.js',
  'js/tools/calculus.js',
  'js/tools/number-theory.js',
  'js/tools/finance.js',
  'js/tools/graphing.js',
  'js/unit-conversions.js',
  'js/storage.js',
  'js/history.js',
  'js/i18n.js',
  'js/state.js',
  'js/keyboard.js',
  'js/app.js'
];

function stripModuleSyntax(code, file) {
  const out = code
    .replace(/^import\s[\s\S]*?\sfrom\s+['"][^'"]+['"];[ \t]*\r?\n/gm, '')
    .replace(/^export\s*\{[\s\S]*?\};?[ \t]*(\r?\n|$)/gm, '');
  if (/^\s*(import|export)\s/m.test(out)) {
    throw new Error(`Unsupported import/export syntax left in ${file}`);
  }
  return out.trim();
}

const bundle = MODULES.map((file) => stripModuleSyntax(read(file), file)).join('\n\n');

let html = read('index.html');
html = html.replace(/<link rel="stylesheet" href="(css\/[^"]+)" \/>/g, (_, href) => `<style>\n${read(href).trim()}\n</style>`);
html = html.replace(/\s*<link rel="manifest" href="manifest.json" \/>/, '');
html = html.replace(/<script type="module" src="js\/app.js"><\/script>\s*<script>[\s\S]*?<\/script>/,
  `<script>\n(function () {\n'use strict';\n${bundle}\n})();\n</script>`);
html = html.replace('<html lang="pt-BR"', '<!-- Generated by scripts/build-standalone.mjs from index.html — do not edit by hand. -->\n<html lang="pt-BR"');

if (/<script type="module"/.test(html) || /<link rel="stylesheet" href="css\//.test(html)) {
  throw new Error('standalone.html still references external modules or stylesheets');
}

fs.writeFileSync(path.join(rootDir, 'standalone.html'), html);
console.log(`standalone.html built (${(html.length / 1024).toFixed(0)} KB, ${MODULES.length} modules inlined).`);
